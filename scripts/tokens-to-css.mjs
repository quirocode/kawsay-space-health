// Generates src/app/tokens.css from design/exports/tokens.json (P4's pen.dev variables).
// Run: node scripts/tokens-to-css.mjs   — re-run whenever P4 updates the tokens.
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync(new URL('../design/exports/tokens.json', import.meta.url), 'utf8'));

// App variable ← design token. Components only use the app names.
const MAP = {
  '--bg': 'bg',
  '--surface': 'surface-1',
  '--surface-2': 'surface-2',
  '--surface-3': 'surface-3',
  '--line': 'border',
  '--ink': 'text',
  '--ink-2': 'text-muted',
  '--brand': 'inti',
  '--on-brand': 'on-inti',
  '--brand-bg': 'inti-bg',
  '--brand-ink': 'inti-ink', // NASA blue for text and outlines; a lighter tint at night, where #0B3D91 is unreadable
  '--future': 'inti-ink', // decision: the arrival-day self is drawn in the brand colour; violet stays reserved for stale data
  '--status-ok': 'green',
  '--status-watch': 'yellow',
  '--status-act': 'red',
  '--status-stale': 'stale',
  '--status-ok-bg': 'green-bg',
  '--status-watch-bg': 'yellow-bg',
  '--status-act-bg': 'red-bg',
  '--status-stale-bg': 'stale-bg',
  '--zone-ok': 'zone-ok',
  '--figure-base': 'figure-base',
  '--figure-line': 'figure-line',
};

const block = (key) => Object.entries(MAP).map(([css, tok]) => `  ${css}: ${t.color[tok][key]};`).join('\n');

const css = `/* GENERATED by scripts/tokens-to-css.mjs from design/exports/tokens.json — do not edit by hand. */
:root {
${block('light')}
  --radius: ${t.radius.default}px;
  --radius-sm: ${t.radius.sm}px;
  color-scheme: light;
}

:root[data-theme='night'] {
${block('night')}
  color-scheme: dark;
}
`;
writeFileSync(new URL('../src/app/tokens.css', import.meta.url), css);
console.log('wrote src/app/tokens.css');
